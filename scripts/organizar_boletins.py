def normalize(nome: str) -> str | None:
    """Extrai o número normalizado (sem zeros à esquerda) de um nome BS-<num>-2025.pdf."""
    m = re.match(r"BS-([0-9.]+)-2025\.pdf", nome)
    if not m:
        return None
    num = m.group(1)
    if "." in num:
        inteiro, sufixo = num.split(".", 1)
        return f"{int(inteiro)}.{sufixo}"
    return str(int(num))


def main():
    src = Path("/opt/data/hermes-data/boletins_tmp_2025")
    dest = Path("/opt/data/hermes-data/boletins")
    if not src.is_dir():
        print("Pasta temporária não existe — nada a fazer.")
        return
    movidos, sem_map = 0, []
    for pdf in sorted(src.glob("*.pdf")):
        num = normalize(pdf.name)
        if num is None:
            sem_map.append(pdf.name)
            continue
        data = MAP.get(num)
        if not data:
            sem_map.append(f"{pdf.name} (sem data)")
            continue
        pasta = dest / data
        pasta.mkdir(parents=True, exist_ok=True)
        alvo = pasta / pdf.name
        if alvo.exists():
            pdf.unlink()
        else:
            pdf.rename(alvo)
        movidos += 1
    print(f"Movidos: {movidos}")
    if sem_map:
        print("Sem mapeamento:")
        for s in sem_map:
            print("  ", s)


if __name__ == "__main__":
    main()
