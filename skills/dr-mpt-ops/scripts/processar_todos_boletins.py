def extrair_texto_pdf(pdf_path: Path) -> str:
    doc = fitz.open(pdf_path)
    partes = []
    for i in range(len(doc)):
        page = doc[i]
        texto = page.get_text("text").strip()
        if texto:
            partes.append(f"## Página {i+1}\n\n{texto}")
        else:
            partes.append(f"## Página {i+1}\n\n*[Página sem texto extraível]*")
    doc.close()
    return "\n\n".join(partes)

def processar_pdf(pdf_path: Path):
    m = PDF_PATTERN.match(pdf_path.name)
    if not m:
        print(f"  ⚠️  Nome não reconhecido: {pdf_path.name}")
        return False
    num = m.group(1)
    data = ALL_BOLETINS.get(num)
    if not data:
        print(f"  ⚠️  Sem data mapeada para {num} ({pdf_path.name})")
        return False
    
    pasta = BOLETINS_DIR / data
    pasta.mkdir(parents=True, exist_ok=True)
    
    md_path = pasta / f"BS-{num}-{m.group(2)}.md"
    if md_path.exists():
        print(f"  ⏭️  MD já existe: {md_path.name}")
        return True
    
    print(f"  📄 Processando {pdf_path.name} -> {data}...")
    texto = extrair_texto_pdf(pdf_path)
    md_path.write_text(texto, encoding="utf-8")
    print(f"     ✅ {md_path}")
    return True

def main():
    pdfs = list(BOLETINS_DIR.glob("BS-*-2025.pdf")) + list(BOLETINS_DIR.glob("BS-*-2026.pdf"))
    print(f"Encontrados {len(pdfs)} PDFs para processar")
    for pdf in sorted(pdfs):
        processar_pdf(pdf)
    print("✅ Concluído")

if __name__ == "__main__":
    main()